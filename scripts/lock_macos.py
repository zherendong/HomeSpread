"""Record the installed runtime dependency closure, excluding build/test tools.

Run deliberately after upgrading dependencies and auditing them. Builds consume
the checked-in lock file; they never regenerate it or silently upgrade packages.
"""
from importlib.metadata import distribution
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def main():
    pending = ["pymobiledevice3", "PySide6-Essentials"]
    found = {}
    while pending:
        name = canonicalize_name(pending.pop())
        if name in found:
            continue
        dist = distribution(name)
        found[name] = dist.version
        for text in dist.requires or []:
            req = Requirement(text)
            if req.marker is None or req.marker.evaluate({"extra": ""}):
                pending.append(req.name)
    lines = ["# macOS arm64 / CPython 3.12 runtime dependency snapshot.",
             "# Generated by scripts/lock_macos.py; refresh deliberately after audit."]
    lines += [f"{name}=={version}" for name, version in sorted(found.items())]
    (ROOT / "requirements-macos.lock").write_text("\n".join(lines) + "\n")
    print(f"Locked {len(found)} runtime packages")


if __name__ == "__main__":
    main()
